-- Usuários do Ask.IA.
-- O login aceita e-mail OU nome (decidido pelo "@" no backend), então o nome
-- também precisa ser único — sem diferenciar maiúsculas de minúsculas
-- ("Jorge" e "jorge" são a mesma pessoa).

CREATE TABLE tb_users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255),
    email    VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE UNIQUE INDEX ux_users_name_lower ON tb_users (lower(name));
