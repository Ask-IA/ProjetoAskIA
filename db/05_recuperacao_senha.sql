-- "Esqueci minha senha": o token enviado por e-mail NUNCA é guardado em
-- texto puro no banco — só o hash (SHA-256) dele. Assim, mesmo um vazamento
-- do banco não dá a ninguém um token válido pronto para usar.
-- Cada token expira em 30 minutos (ver PasswordResetService) e é apagado
-- assim que usado (ou ao pedir um novo — só o último pedido vale).

CREATE TABLE tb_tokens_redefinicao_senha (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES tb_users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE, -- hex do SHA-256 (64 caracteres)
    expira_em   TIMESTAMP(6) NOT NULL,
    criado_em   TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_tokens_redefinicao_usuario ON tb_tokens_redefinicao_senha (usuario_id);
