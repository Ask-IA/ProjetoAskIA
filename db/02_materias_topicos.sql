-- Matérias (com cor, escolhida em rodízio pelo backend) e os tópicos de cada
-- uma, que o aluno marca como concluído em Matérias.

CREATE TABLE tb_materias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    cor        VARCHAR(7)   NOT NULL,
    usuario_id BIGINT       NOT NULL REFERENCES tb_users (id)
);

CREATE TABLE tb_topicos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    concluido  BOOLEAN      NOT NULL DEFAULT FALSE,
    materia_id BIGINT       NOT NULL REFERENCES tb_materias (id)
);
