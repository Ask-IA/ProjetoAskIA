-- Metas semanais (dia + hora de estudar uma matéria) e sessões de estudo
-- registradas pelo aluno (usadas também pela ofensiva da gamificação).

CREATE TABLE tb_metas_estudo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL REFERENCES tb_users (id),
    materia_id BIGINT      NOT NULL REFERENCES tb_materias (id),
    dia        VARCHAR(10) NOT NULL,
    hora       VARCHAR(5)  NOT NULL,
    descricao  VARCHAR(200)
);

CREATE TABLE tb_sessoes_estudo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES tb_users (id),
    materia_id BIGINT       NOT NULL REFERENCES tb_materias (id),
    minutos    INTEGER      NOT NULL,
    anotacoes  VARCHAR(300),
    data       TIMESTAMP(6) NOT NULL
);
